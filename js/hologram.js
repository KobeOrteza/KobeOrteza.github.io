/* hologram.js — renders Kobe's portrait as a living hologram of 1s and 0s.
   Data comes from js/hologram-data.js (generated by tools/make-hologram.swift). */
(() => {
  "use strict";
  const KOBE = window.KOBE || {};
  const DATA = window.HOLOGRAM_DATA;
  const stage = document.getElementById("holo-stage");
  const frame = document.getElementById("holo-frame");
  const canvas = document.getElementById("hologram");
  const countEl = document.getElementById("holo-count");
  if (!DATA || !canvas || !frame) return;
  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  const reduceMotion = !!KOBE.reduceMotion;
  const CYAN = [87, 216, 206];
  const ICE = [205, 255, 250];
  const COPPER = [224, 144, 79];
  const LEVELS = 10;

  let W = 0, H = 0, dpr = 1, cell = 6;
  let ghost = null;           // smooth cyan-tinted copy of the portrait, drawn under the bits
  let ghostImg = null;        // high-res cut-out duotone (assets/kobe-holo.png), preferred when loaded
  let hoverClarity = 0;       // rises while the pointer is over the hologram
  let pointerOver = false;
  const img = new Image();
  img.decoding = "async";
  img.onload = () => {
    // feather the edges so the portrait dissolves into the projector beam (no hard crop lines)
    const c = document.createElement("canvas");
    c.width = img.naturalWidth; c.height = img.naturalHeight;
    const g = c.getContext("2d");
    g.drawImage(img, 0, 0);
    g.globalCompositeOperation = "destination-in";
    const v = g.createLinearGradient(0, 0, 0, c.height);
    v.addColorStop(0, "rgba(0,0,0,1)");
    v.addColorStop(0.68, "rgba(0,0,0,1)");
    v.addColorStop(1, "rgba(0,0,0,0)");
    g.fillStyle = v;
    g.fillRect(0, 0, c.width, c.height);
    const h = g.createLinearGradient(0, 0, c.width, 0);
    h.addColorStop(0, "rgba(0,0,0,0)");
    h.addColorStop(0.1, "rgba(0,0,0,1)");
    h.addColorStop(0.9, "rgba(0,0,0,1)");
    h.addColorStop(1, "rgba(0,0,0,0)");
    g.fillStyle = h;
    g.fillRect(0, 0, c.width, c.height);
    ghostImg = c;
  };
  img.src = "assets/kobe-holo.png";
  let drawRect = { x: 0, y: 0, w: 0, h: 0 };
  let particles = [];
  let dust = [];
  let sprites = null;     // sprites[colorIndex][char][level] -> canvas
  let spriteSize = 0;
  let running = false, visible = true, raf = 0;
  let disabled = false; // set when the 3D hologram (holo3d.js) takes over
  KOBE.stopHolo2D = () => {
    disabled = true;
    running = false;
    if (raf) cancelAnimationFrame(raf);
    raf = 0;
  };
  let introStart = 0;
  let nextGlitch = 0, glitchUntil = 0;
  let tiltX = 0, tiltY = 0;
  let scanPattern = null;

  /* ---------- Decode the packed grid ---------- */
  const alpha = DATA.alphabet;
  const decode = (str) => {
    const out = new Float32Array(str.length);
    for (let i = 0; i < str.length; i++) out[i] = alpha.indexOf(str[i]) / 63;
    return out;
  };
  const srcLum = decode(DATA.lum);
  const srcMask = decode(DATA.mask);

  const sample = (cols, rows) => {
    const lum = new Float32Array(cols * rows);
    const mask = new Float32Array(cols * rows);
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        const x0 = Math.floor((c / cols) * DATA.cols), x1 = Math.max(x0 + 1, Math.floor(((c + 1) / cols) * DATA.cols));
        const y0 = Math.floor((r / rows) * DATA.rows), y1 = Math.max(y0 + 1, Math.floor(((r + 1) / rows) * DATA.rows));
        let l = 0, m = 0, n = 0;
        for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
          const i = y * DATA.cols + x;
          l += srcLum[i]; m += srcMask[i]; n++;
        }
        lum[r * cols + c] = l / n;
        mask[r * cols + c] = m / n;
      }
    }
    return { lum, mask };
  };

  /* ---------- Glyph sprites (pre-rendered with glow) ---------- */
  const buildSprites = (fontPx) => {
    spriteSize = Math.ceil(fontPx * 2.2);
    const colors = [CYAN, ICE, COPPER];
    sprites = colors.map((rgb) => ["0", "1"].map((ch) => {
      const lv = [];
      for (let l = 0; l < LEVELS; l++) {
        const a = (l + 1) / LEVELS;
        const s = document.createElement("canvas");
        s.width = s.height = spriteSize;
        const g = s.getContext("2d");
        g.font = `600 ${fontPx}px "IBM Plex Mono", ui-monospace, monospace`;
        g.textAlign = "center";
        g.textBaseline = "middle";
        g.shadowColor = `rgba(${rgb[0]},${rgb[1]},${rgb[2]},${Math.min(1, a * 1.2)})`;
        g.shadowBlur = fontPx * 0.55 * a + 1;
        g.fillStyle = `rgba(${rgb[0]},${rgb[1]},${rgb[2]},${a})`;
        g.fillText(ch, spriteSize / 2, spriteSize / 2 + fontPx * 0.04);
        lv.push(s);
      }
      return lv;
    }));
  };

  /* ---------- Layout ---------- */
  const build = () => {
    const rect = frame.getBoundingClientRect();
    W = Math.max(200, rect.width);
    H = Math.max(260, rect.height);
    dpr = Math.min(window.devicePixelRatio || 1, 1.25);
    canvas.width = Math.round(W * dpr);
    canvas.height = Math.round(H * dpr);
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

    // dense grid: the face spans ~45 columns on desktop so features stay readable
    const cols = W < 330 ? 56 : W < 420 ? 64 : 72;
    const imgAspect = DATA.cols / DATA.rows; // width / height of the cropped portrait
    let drawH = H;
    let drawW = drawH * imgAspect;
    if (drawW > W) { drawW = W; drawH = drawW / imgAspect; }
    cell = drawW / cols;
    const rows = Math.round(drawH / cell);
    const ox = (W - drawW) / 2;
    const oy = H - drawH;
    drawRect = { x: ox, y: oy, w: drawW, h: drawH };

    const { lum, mask } = sample(cols, rows);
    buildSprites(Math.max(5, cell * 1.32) * dpr);
    buildGhost();

    const old = particles;
    particles = [];
    const isIn = (c, r) => c >= 0 && r >= 0 && c < cols && r < rows && mask[r * cols + c] > 0.3;
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        const i = r * cols + c;
        if (mask[i] <= 0.3) continue;
        // bottom fade so the bust dissolves into the projector beam
        const fade = Math.min(1, (rows - r) / (rows * 0.2));
        const rightEdge = !isIn(c + 1, r) || !isIn(c + 2, r);
        const leftEdge = !isIn(c - 1, r) || !isIn(c - 2, r);
        // upper half (face + hair) is kept bright; the white shirt is toned down so it doesn't steal focus
        const l = r < rows * 0.5 ? Math.min(1, Math.pow(lum[i], 0.85) * 1.05) : lum[i] * 0.78;
        const tx = ox + c * cell + cell / 2;
        const ty = oy + r * cell + cell / 2;
        particles.push({
          tx, ty,
          x: tx, y: ty, vx: 0, vy: 0,
          lum: l,
          a: Math.min(1, (0.14 + 0.86 * Math.pow(l, 1.35)) * Math.min(1, mask[i] * 1.3) * fade),
          color: rightEdge ? 2 : (leftEdge || l > 0.88 ? 1 : 0),
          size: 0.82 + 0.38 * l + (rightEdge || leftEdge ? 0.12 : 0),
          ch: Math.random() < 0.5 ? 0 : 1,
          lockAt: 0,
          rainY: 0, rainSpeed: 0
        });
      }
    }
    // keep intro state on resize
    if (old.length && introStart) particles.forEach((p) => { p.lockAt = 0; });
    else seedIntro();

    dust = [];
    const dustCount = Math.round(W / 6);
    for (let i = 0; i < dustCount; i++) dust.push(newDust(true));

    if (countEl) countEl.textContent = `${particles.length.toLocaleString()} bits`;
  };

  /* Smooth, cyan-tinted ghost of the portrait (full-res grid, upscaled with smoothing).
     Drawn faintly under the digits so the face is instantly recognisable. */
  const buildGhost = () => {
    const g = document.createElement("canvas");
    g.width = DATA.cols; g.height = DATA.rows;
    const gx = g.getContext("2d");
    const img = gx.createImageData(DATA.cols, DATA.rows);
    for (let i = 0; i < srcLum.length; i++) {
      const r = Math.floor(i / DATA.cols);
      const m = Math.max(0, Math.min(1, (srcMask[i] - 0.2) * 1.6));
      const fade = Math.min(1, (DATA.rows - r) / (DATA.rows * 0.22));
      const l = Math.pow(srcLum[i], 1.2) * (r < DATA.rows * 0.5 ? 1 : 0.7);
      img.data[i * 4] = 60 + 150 * l;
      img.data[i * 4 + 1] = 150 + 105 * l;
      img.data[i * 4 + 2] = 150 + 100 * l;
      img.data[i * 4 + 3] = 255 * m * fade * (0.25 + 0.75 * l);
    }
    gx.putImageData(img, 0, 0);
    ghost = g;
  };

  const newDust = (anywhere) => ({
    x: W / 2 + (Math.random() - 0.5) * W * 0.9,
    y: anywhere ? Math.random() * H : H + 10,
    v: 0.15 + Math.random() * 0.45,
    ch: Math.random() < 0.5 ? 0 : 1,
    a: 0.05 + Math.random() * 0.18
  });

  const seedIntro = () => {
    introStart = performance.now();
    particles.forEach((p) => {
      p.x = p.tx + (Math.random() - 0.5) * 24;
      p.rainY = -Math.random() * H * 1.2;
      p.y = p.rainY;
      p.rainSpeed = 0.35 + Math.random() * 0.55;
      // lock top-to-bottom with jitter, like a scan resolving the image
      p.lockAt = introStart + 500 + (p.ty / H) * 1500 + Math.random() * 700;
      p.vx = p.vy = 0;
    });
  };

  /* ---------- Interaction ---------- */
  const local = { x: -9999, y: -9999, nx: 0, ny: 0 };
  const updatePointer = (e) => {
    const r = canvas.getBoundingClientRect();
    local.x = e.clientX - r.left;
    local.y = e.clientY - r.top;
  };
  window.addEventListener("pointermove", (e) => {
    if (!stage) return;
    const r = stage.getBoundingClientRect();
    local.nx = Math.max(-1, Math.min(1, ((e.clientX - r.left) / r.width - 0.5) * 2));
    local.ny = Math.max(-1, Math.min(1, ((e.clientY - r.top) / r.height - 0.5) * 2));
    updatePointer(e);
  }, { passive: true });
  canvas.addEventListener("pointerenter", () => { pointerOver = true; });
  canvas.addEventListener("pointerleave", () => { pointerOver = false; local.x = local.y = -9999; });

  // Click / tap: blast the bits apart, they re-assemble.
  canvas.addEventListener("pointerdown", (e) => {
    if (reduceMotion) return;
    updatePointer(e);
    KOBE.sfx && KOBE.sfx("scatter");
    particles.forEach((p) => {
      const dx = p.x - local.x, dy = p.y - local.y;
      const d = Math.hypot(dx, dy) + 0.001;
      const f = Math.max(0, 1 - d / (W * 0.8)) * 22;
      p.vx += (dx / d) * f + (Math.random() - 0.5) * 6;
      p.vy += (dy / d) * f + (Math.random() - 0.5) * 6;
      if (Math.random() < 0.5) p.ch ^= 1;
    });
  });

  /* ---------- Render ---------- */
  const drawGlyph = (colorIdx, ch, a, x, y, scale) => {
    if (a < 0.06) return;
    const lvl = Math.max(0, Math.min(LEVELS - 1, Math.round(a * LEVELS) - 1));
    const s = (spriteSize / dpr) * scale;
    ctx.drawImage(sprites[colorIdx][ch][lvl], x - s / 2, y - s / 2, s, s);
  };

  const render = (now) => {
    ctx.clearRect(0, 0, W, H);
    ctx.globalCompositeOperation = "lighter";

    // drifting data dust inside the beam
    for (const d of dust) {
      if (!reduceMotion) {
        d.y -= d.v;
        if (d.y < -10) Object.assign(d, newDust(false));
        if (Math.random() < 0.01) d.ch ^= 1;
      }
      drawGlyph(0, d.ch, d.a, d.x, d.y, 0.55);
    }

    // Clear portrait underneath — fades in as the bits lock. Every ~7s it "decodes"
    // to near full clarity, and hovering the hologram keeps it clear.
    const portrait = ghostImg || ghost;
    let clarity = 0;
    if (portrait) {
      const t = reduceMotion ? 1 : Math.max(0, Math.min(1, (now - introStart - 1500) / 1200));
      const cyc = reduceMotion ? 0 : ((now - introStart) % 7000) / 7000;
      const pulse = cyc > 0.72 && cyc < 0.92 ? Math.sin(((cyc - 0.72) / 0.2) * Math.PI) : 0;
      hoverClarity += ((pointerOver ? 1 : 0) - hoverClarity) * 0.08;
      clarity = Math.max(pulse, hoverClarity);
      if (t > 0) {
        const base = ghostImg ? 0.62 : 0.36;
        ctx.globalAlpha = Math.min(1, (base + (1 - base) * clarity) * t * (reduceMotion ? 1 : 0.94 + Math.random() * 0.06));
        ctx.imageSmoothingEnabled = true;
        ctx.imageSmoothingQuality = "high";
        ctx.drawImage(portrait, drawRect.x, drawRect.y, drawRect.w, drawRect.h);
        ctx.globalAlpha = 1;
      }
    }
    // bits thin out while the portrait is at full clarity
    const bitAlpha = ghostImg ? 0.72 - clarity * 0.45 : 1;

    const repelR = Math.max(44, W * 0.11);
    const flicker = reduceMotion ? 1 : 0.93 + Math.random() * 0.07;
    // scan bar that sweeps down the body every ~4.5s, brightening the bits it passes
    const sweepY = reduceMotion ? -999 : ((now % 4500) / 4500) * (H * 1.3) - H * 0.15;

    for (let i = 0; i < particles.length; i++) {
      const p = particles[i];
      if (!reduceMotion) {
        if (now < p.lockAt) {
          // raining phase
          p.rainY += p.rainSpeed * 9;
          if (p.rainY > H + 20) p.rainY = -20 - Math.random() * 60;
          p.y = p.rainY;
          p.x = p.tx + Math.sin((p.rainY + i) * 0.02) * 2;
          if (Math.random() < 0.3) p.ch ^= 1;
          drawGlyph(0, p.ch, 0.25 + p.lum * 0.25, p.x, p.y, 0.8);
          continue;
        }
        // spring back to the exact target so the face never warps
        let ax = (p.tx - p.x) * 0.09;
        let ay = (p.ty - p.y) * 0.09;
        const dx = p.x - local.x, dy = p.y - local.y;
        const d2 = dx * dx + dy * dy;
        if (d2 < repelR * repelR) {
          const d = Math.sqrt(d2) + 0.001;
          const f = (1 - d / repelR) * 1.8;
          ax += (dx / d) * f;
          ay += (dy / d) * f;
        }
        p.vx = (p.vx + ax) * 0.82;
        p.vy = (p.vy + ay) * 0.82;
        p.x += p.vx;
        p.y += p.vy;
        if (Math.random() < 0.004) p.ch ^= 1;
      }
      // a brighter "just locked" flash fades over ~400ms
      const since = now - p.lockAt;
      let flash = !reduceMotion && since < 400 ? (1 - since / 400) * 0.6 : 0;
      const ds = p.y - sweepY;
      if (ds < 0 && ds > -40) flash += (1 + ds / 40) * 0.45;
      drawGlyph(flash > 0.25 ? 1 : p.color, p.ch, Math.min(1, p.a * flicker * bitAlpha + flash), p.x, p.y, p.size);
    }

    // hologram scanlines: carve thin dark lines out of the drawn bits only
    ctx.globalCompositeOperation = "destination-out";
    if (!scanPattern) {
      const sp = document.createElement("canvas");
      sp.width = 4; sp.height = 3;
      const sg = sp.getContext("2d");
      sg.fillStyle = "rgba(0,0,0,.2)";
      sg.fillRect(0, 0, 4, 1);
      scanPattern = ctx.createPattern(sp, "repeat");
    }
    const off = reduceMotion ? 0 : Math.floor((now / 60) % 3);
    ctx.save();
    ctx.translate(0, off);
    ctx.fillStyle = scanPattern;
    ctx.fillRect(0, -3, W, H + 3);
    ctx.restore();

    ctx.globalCompositeOperation = "source-over";

    // occasional horizontal glitch slices
    if (!reduceMotion) {
      if (now > nextGlitch) {
        glitchUntil = now + 90 + Math.random() * 120;
        nextGlitch = now + 2600 + Math.random() * 4200;
      }
      if (now < glitchUntil) {
        for (let k = 0; k < 3; k++) {
          const sy = Math.random() * H, sh = 4 + Math.random() * 18;
          const shift = (Math.random() - 0.5) * 26;
          ctx.drawImage(canvas, 0, sy * dpr, W * dpr, sh * dpr, shift, sy, W, sh);
        }
      }
    }
  };

  const loop = (now) => {
    raf = 0;
    if (!running || !visible || document.hidden) return;
    // smooth 3D tilt of the frame toward the pointer
    tiltX += (local.nx * 9 - tiltX) * 0.08;
    tiltY += (-local.ny * 6 - tiltY) * 0.08;
    frame.style.transform = `rotateY(${tiltX.toFixed(2)}deg) rotateX(${tiltY.toFixed(2)}deg)`;
    render(now);
    raf = requestAnimationFrame(loop);
  };
  const kick = () => { if (!raf && running && visible && !document.hidden) raf = requestAnimationFrame(loop); };

  /* ---------- Lifecycle ---------- */
  const start = () => {
    if (disabled) return;
    build();
    if (reduceMotion) {
      particles.forEach((p) => { p.x = p.tx; p.y = p.ty; p.lockAt = 0; });
      render(performance.now());
      return;
    }
    running = true;
    kick();
  };

  if ("IntersectionObserver" in window) {
    new IntersectionObserver(([entry]) => { visible = entry.isIntersecting; kick(); }, { threshold: 0 }).observe(frame);
  }
  document.addEventListener("visibilitychange", kick);

  let resizeTimer;
  let lastW = 0;
  window.addEventListener("resize", () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => {
      const w = frame.getBoundingClientRect().width;
      if (Math.abs(w - lastW) < 2) return;
      lastW = w;
      build();
      if (reduceMotion) render(performance.now());
    }, 200);
  });

  const go = () => {
    lastW = frame.getBoundingClientRect().width;
    // wait for the mono font so glyph sprites use it
    const ready = document.fonts && document.fonts.load ? document.fonts.load('600 12px "IBM Plex Mono"').catch(() => {}) : Promise.resolve();
    ready.then(start);
  };
  if (KOBE.onBoot) KOBE.onBoot(go); else go();
})();
